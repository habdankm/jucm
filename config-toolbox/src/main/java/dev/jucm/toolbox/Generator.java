package dev.jucm.toolbox;

import dev.jucm.core.ConfigConstraint;
import dev.jucm.core.ConfigDefinition;
import dev.jucm.core.ConfigField;
import dev.jucm.core.ConfigPath;
import dev.jucm.core.ConfigType;
import dev.jucm.core.ConfigValue;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

/**
 * `config-generate`: a sample, CORRECT YAML file built from the model alone — without a separate
 * template and without starting the application.
 *
 * <ul>
 *   <li><b>secrets</b>: a field recognised by name (`key`, `token`, `password`, `secret`) gets a
 *       placeholder in angle brackets, for example {@code "<provide-api_key>"}. A sample value must
 *       NEVER look like a real secret.</li>
 *   <li><b>order of value sources</b>: first the CONSTRAINT (`in[…]` gives the first allowed value),
 *       then the DEFAULT value from the declaration, and finally an example from the type. Thanks to
 *       that the file satisfies the rules instead of being "pretty but rejected".</li>
 *   <li><b>comments SINGLE-LINE</b>: the marker (`CONST(…)` / `TCONF(…)`) stands BEFORE the description
 *       text, on the same line as the value: {@code port: 443   # CONST(in[8080,443]) Service port.}
 *       That is why a description can never pretend to be a marker — the reader recognises sections
 *       from the START of the comment, and here the start is always a marker or nothing at all.</li>
 * </ul>
 *
 * <p>The result is **identical byte for byte** — no randomness, no time, no order depending on the JVM
 * (fields are sorted by address, as everywhere else in this project).
 */
final class Generator {

    /** The column where we put `#` — fixed, so the file is comparable between runs. */
    private static final int COMMENT_COLUMN = 26;

    /** These parts of a field name tell us that a sample value must not look like a secret. */
    private static final List<String> SECRET_WORDS = List.of("key", "token", "password", "passwd", "secret");

    private Generator() {
    }

    static String yaml(ConfigDefinition definition) {
        StringBuilder text = new StringBuilder();
        text.append("# Generated by `config-generate` (JUCM) — a starting point that matches the model.\n");
        text.append("# Values: first from the `in[…]` rule, then from the default value, and finally an example.\n");

        List<ConfigField> fields = new ArrayList<>(definition.fields());
        fields.sort((one, other) -> ConfigPath.BY_VALUE.compare(one.path(), other.path()));

        List<String> previousPrefix = List.of();
        for (ConfigField field : fields) {
            List<String> segments = List.of(field.path().canonical().split("\\."));
            List<String> prefix = segments.subList(0, segments.size() - 1);
            // Nested blocks: we print ONLY the new segments (fields are sorted, so the common prefix
            // grows and shrinks monotonically — as in a tree walk).
            int common = commonPrefix(previousPrefix, prefix);
            for (int index = common; index < prefix.size(); index++) {
                text.append("  ".repeat(index)).append(prefix.get(index)).append(":\n");
            }
            previousPrefix = prefix;

            String value = example(field);
            text.append("  ".repeat(prefix.size())).append(segments.get(segments.size() - 1))
                .append(": ").append(value);
            String comment = comment(field);
            if (!comment.isEmpty()) {
                int at = "  ".repeat(prefix.size()).length() + segments.get(segments.size() - 1).length() + 2 + value.length();
                text.append(" ".repeat(Math.max(2, COMMENT_COLUMN - at)));
                text.append("# ").append(comment);
            }
            text.append('\n');
        }
        return text.toString();
    }

    /**
     * The comment next to a value: markers FIRST, then the description. A marker with no value has
     * nothing to carry, so it stays silent — and a description without markers cannot pretend to be one
     * anyway, because it stands after them.
     */
    private static String comment(ConfigField field) {
        StringBuilder text = new StringBuilder();
        field.transformerConfig().ifPresent(config -> text.append("TCONF(").append(config).append(") "));
        rule(field).ifPresent(chain -> text.append("CONST(").append(chain).append(") "));
        if (!field.description().isBlank()) {
            text.append(field.description().strip());
        }
        return text.toString().strip();
    }

    /** A field rule as a chain — one rule is its chain, several are joined with `&` (validation requires all of them). */
    private static Optional<String> rule(ConfigField field) {
        StringBuilder chain = new StringBuilder();
        for (ConfigConstraint constraint : field.constraints()) {
            if (chain.length() > 0) {
                chain.append('&');
            }
            chain.append(constraint instanceof ConfigConstraint.Const constant ? constant.chain() : "");
        }
        return chain.length() == 0 ? Optional.empty() : Optional.of(chain.toString());
    }

    /**
     * A sample value — in this order: RULE, then DEFAULT, and finally the type.
     * A secret never gets a value that could pass for a real one.
     */
    static String example(ConfigField field) {
        if (isSecret(field)) {
            return "\"<provide-" + field.path().canonical().replace('.', '_') + ">\"";
        }
        Optional<String> fromRule = rule(field).flatMap(chain -> firstAllowed(chain, field.type()));
        if (fromRule.isPresent()) {
            return quoteIfText(fromRule.get(), field.type());
        }
        if (field.defaultValue().isPresent()) {
            return literal(field.defaultValue().get(), field.type());
        }
        return byType(field);
    }

    /** The first value allowed by `in[…]` — we ask the CONSTRAINT, not the text (the view asks the model too). */
    private static Optional<String> firstAllowed(String chain, ConfigType type) {
        try {
            return new ConfigConstraint.Const(chain).allowedValues().flatMap(values -> values.stream().findFirst());
        } catch (IllegalArgumentException broken) {
            return Optional.empty();   // an unparsable chain is a declaration error — validation will report it
        }
    }

    /**
     * A value from the declaration: strings in quotes, numbers and booleans without — as in the YAML
     * sample. A `${…}` pattern stays a pattern: the declaration supplies the type anyway, and
     * interpolation is meant to resolve in the application.
     */
    private static String literal(ConfigValue value, ConfigType type) {
        return switch (type) {
            case STR, URI, DURATION, TIMESTAMP, BINARY ->
                "\"" + value.display().replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
            case SEQ, MAP -> value.display();
            default -> value.display();
        };
    }

    private static String quoteIfText(String allowed, ConfigType type) {
        return switch (type) {
            case STR, URI, DURATION, TIMESTAMP, BINARY -> "\"" + allowed + "\"";
            default -> allowed;
        };
    }

    /** An example from the type itself (when there is neither a rule nor a default value). */
    private static String byType(ConfigField field) {
        String canonical = field.path().canonical().toLowerCase(Locale.ROOT);
        String last = canonical.substring(canonical.lastIndexOf('.') + 1);
        if (last.equals("host")) {
            return "\"localhost\"";
        }
        if (last.equals("uri") || last.equals("url")) {
            return "\"https://example.com/api\"";
        }
        if (last.equals("port")) {
            return "443";
        }
        return switch (field.type()) {
            case STR -> "\"example\"";
            case INT -> Integer.toString(1000 + Math.floorMod(canonical.hashCode(), 900));
            case FLOAT -> "1.0";
            case BOOL -> "false";
            case TIMESTAMP -> "\"2030-01-01T00:00:00Z\"";
            case DURATION -> "\"30s\"";
            case URI -> "\"https://example.com/api\"";
            case SEQ -> "[a, b]";
            case MAP -> "{a: 1}";
            case BINARY -> "\"AA==\"";
        };
    }

    private static boolean isSecret(ConfigField field) {
        String canonical = field.path().canonical().toLowerCase(Locale.ROOT);
        return SECRET_WORDS.stream().anyMatch(canonical::contains)
            && switch (field.type()) {
                case STR, URI, BINARY -> true;
                default -> false;
            };
    }

    private static int commonPrefix(List<String> first, List<String> second) {
        int length = Math.min(first.size(), second.size());
        int index = 0;
        while (index < length && first.get(index).equals(second.get(index))) {
            index++;
        }
        return index;
    }
}
